x=input('Digite algo: ')
print('O tipo primitivo desse valor é ', type(x))
print('Só tem espaços? ',x.isspace())
print('É um alfanumérico? ',x.isalnum())
print('Contém apenas letras? ',x.isalpha())
print('É um número decimal? ',x.isdecimal())
print('Está apenas em minúsculo? ',x.islower())
print('Está apenas em maiúsculas? ',x.isupper())
print('Contém apenas números? ',x.isnumeric())
print('Está capitalizada? ',x.istitle())